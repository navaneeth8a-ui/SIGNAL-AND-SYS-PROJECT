"""Package the measured 50-trial block-MSE traces for the offline browser replay."""
from __future__ import annotations

import argparse
import base64
import json
from pathlib import Path

import numpy as np


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", default=".", help="Folder containing replay_trials.npz and results.json")
    parser.add_argument("--output", default="demo/experiment_data.js")
    args = parser.parse_args()
    source = Path(args.source)
    raw = np.load(source / "replay_trials.npz")
    results = json.loads((source / "results.json").read_text(encoding="utf-8"))
    mus = [int(x) for x in raw["mus"]]
    attenuation: dict[str, str] = {}
    positions: dict[str, list[list[int]]] = {}
    for mu in mus:
        on = raw[f"on_mu_{mu}"].astype(np.float64)
        off = raw[f"off_mu_{mu}"].astype(np.float64)
        db = 10.0 * np.log10(np.maximum(off, 1e-30) / np.maximum(on, 1e-30))
        # Hundredth-dB integer samples keep the browser payload compact while
        # preserving enough precision for a classroom result display.
        quantized = np.rint(np.clip(db, -300.0, 300.0) * 100).astype("<i2")
        attenuation[str(mu)] = base64.b64encode(quantized.tobytes(order="C")).decode("ascii")
        positions[str(mu)] = raw[f"positions_mu_{mu}"].astype(int).tolist()
    payload = {
        "mus": mus,
        "trials": 50,
        "blocks": 400,
        "switch_block": 100,
        "attenuation": attenuation,
        "positions": positions,
        "results": results,
        "provenance": "Generated by run_part1.py from Part 1 paths, seeds 0–49, white Gaussian reference; attenuation derived per block from saved ANC-on/off MSE.",
    }
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("window.ANC_REPLAY = " + json.dumps(payload, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"Wrote {out} ({out.stat().st_size / 1024:.1f} KiB) with {len(mus)} step sizes × 50 trials × 400 blocks")


if __name__ == "__main__":
    main()
