"""Create clearly-labelled synthetic filters for a pipeline smoke test.

These are NOT results from the Part 1 room simulator. For real experiments use
W.npy generated by the repository's make_dataset.py / run_part1.py workflow.
"""
from __future__ import annotations
import numpy as np


def make_synthetic_filters(n_samples: int = 2048, n_taps: int = 512,
                           seed: int = 2026) -> np.ndarray:
    if n_taps != 512:
        raise ValueError("This project demo expects 512-tap filters")
    rng = np.random.default_rng(seed)
    W = np.zeros((n_samples, n_taps), dtype=np.float32)
    t = np.linspace(0.0, 1.0, n_samples)
    # A moving direct-arrival peak over about 82 taps, plus smooth reflections.
    delay = 66.0 + 82.0 * t
    for i, ti in enumerate(t):
        d = delay[i]
        for offset, amp in [(0.0, 1.0), (17.2, -0.34), (38.5, 0.21), (64.0, -0.12), (95.0, 0.06)]:
            pos = d + offset
            left = int(np.floor(pos))
            frac = pos - left
            env = 0.78 + 0.12 * np.sin(2 * np.pi * ti) + 0.08 * np.cos(4 * np.pi * ti)
            a = amp * env
            if 0 <= left < n_taps:
                W[i, left] += a * (1.0 - frac)
            if 0 <= left + 1 < n_taps:
                W[i, left + 1] += a * frac
        # Smooth low-rank variations mimic changing reflection amplitudes.
        phase = 2 * np.pi * ti
        basis_x = np.arange(n_taps)
        tail = np.exp(-np.maximum(basis_x - d, 0) / 75.0)
        W[i] += (0.035 * np.sin(phase) * np.sin(0.11 * basis_x) +
                 0.02 * np.cos(2 * phase) * np.cos(0.07 * basis_x)) * tail
    # Small, reproducible measurement / simulation variation.
    W += rng.normal(0.0, 0.0008, size=W.shape).astype(np.float32)
    return W


def save_demo(path: str, n_samples: int = 2048, seed: int = 2026) -> np.ndarray:
    W = make_synthetic_filters(n_samples=n_samples, seed=seed)
    np.save(path, W)
    return W
